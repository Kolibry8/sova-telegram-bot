def _season_moment(year: int, k: int) -> datetime:
    """Момент равноденствия/солнцестояния по Москве. k: 0 март, 1 июнь, 2 сентябрь, 3 декабрь."""
    y = (year - 2000) / 1000
    if k == 0:
        jde0 = 2451623.80984 + 365242.37404 * y + 0.05169 * y**2 - 0.00411 * y**3 - 0.00057 * y**4
    elif k == 1:
        jde0 = 2451716.56767 + 365241.62603 * y + 0.00325 * y**2 + 0.00888 * y**3 - 0.00030 * y**4
    elif k == 2:
        jde0 = 2451810.21715 + 365242.01767 * y - 0.11575 * y**2 + 0.00337 * y**3 + 0.00078 * y**4
    else:
        jde0 = 2451900.05952 + 365242.74049 * y - 0.06223 * y**2 - 0.00823 * y**3 + 0.00032 * y**4
    t = (jde0 - 2451545.0) / 36525
    w = 35999.373 * t - 2.47
    dl = 1 + 0.0334 * math.cos(math.radians(w)) + 0.0007 * math.cos(math.radians(2 * w))
    s = sum(a * math.cos(math.radians(b + c * t)) for a, b, c in _TERMS)
    jde = jde0 + 0.00001 * s / dl
    # JDE (земное время) -> UTC (поправка ~69 с) -> МСК
    utc = datetime(2000, 1, 1, 12, tzinfo=timezone.utc) + timedelta(days=jde - 2451545.0, seconds=-69)
    return utc.astimezone(MOSCOW_TZ)


def _seasons(year: int) -> dict:
    names = [
        "Весеннее равноденствие — день равен ночи, астрономическое начало весны (у славян — время Комоедицы и проводов зимы, у кельтов — Остара)",
        "Летнее солнцестояние — самый длинный день и самая короткая ночь года (у славян — купальская пора, у кельтов — Лита)",
        "Осеннее равноденствие — день равен ночи, астрономическое начало осени (праздник урожая, у кельтов — Мабон)",
        "Зимнее солнцестояние — самая длинная ночь года, солнце «поворачивает на лето» (Йоль, у славян — Карачун и Коляда)",
    ]
    out = {}
    for k, name in enumerate(names):
        moment = _season_moment(year, k)
        out.setdefault(moment.date(), []).append(("sky", f"{name}. Точный момент: {moment:%d.%m в %H:%M} МСК"))
    return out


# ─── Сбор праздников на конкретную дату ────────────────────────
_ORDER = {"main": 0, "sky": 1, "fun": 2}


def holidays_on(day) -> list[tuple[str, str]]:
    """Все праздники на дату (date), главные — первыми."""
    items = list(_FIXED.get((day.month, day.day), []))
    items += _movable_church(day.year).get(day, [])
    items += _seasons(day.year).get(day, [])
    items.sort(key=lambda x: _ORDER[x[0]])
    return items


def _fmt(items) -> str:
    return "; ".join(name for _, name in items)


# ─── Нужен ли календарь в этом сообщении ───────────────────────
_TRIGGERS = (
    "праздник", "праздни", "отмечают", "отмечаем", "отмечать", "какой сегодня день",
    "какой завтра день", "что за день", "что сегодня за", "солнцестоян", "равноденств",
    "какое сегодня число и", "знаменательн", "какие даты",
)

_MONTHS = {
    "января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6,
    "июля": 7, "августа": 8, "сентября": 9, "октября": 10, "ноября": 11, "декабря": 12,
}
_DATE_RE = re.compile(r"\b(\d{1,2})\s+(" + "|".join(_MONTHS) + r")\b")


def holidays_context(text: str, now: datetime | None = None) -> str | None:
    """Если спрашивают про праздники — возвращает подсказку для Совы, иначе None."""
    low = text.lower()
    asked_date = _DATE_RE.search(low)
    if not (any(t in low for t in _TRIGGERS) or (asked_date and "день" in low)):
        return None

    now = now or datetime.now(MOSCOW_TZ)
    today = now.date()
    parts = []

    today_items = holidays_on(today)
    parts.append(f"Сегодня ({today:%d.%m}): " + (_fmt(today_items) if today_items else "особых праздников нет"))

    tomorrow = today + timedelta(days=1)
    tm_items = holidays_on(tomorrow)
    if tm_items:
        parts.append(f"Завтра ({tomorrow:%d.%m}): {_fmt(tm_items)}")

    # Конкретная дата из вопроса («что за праздник 7 июля?»)
    if asked_date:
        day, month = int(asked_date.group(1)), _MONTHS[asked_date.group(2)]
        try:
            asked = datetime(today.year, month, day).date()
            if asked < today:
                asked = datetime(today.year + 1, month, day).date()
            items = holidays_on(asked)
            parts.append(f"{asked:%d.%m}: " + (_fmt(items) if items else "особых праздников нет"))
        except ValueError:
            pass

    # Ближайшая неделя — только главное и небесное (чтобы не раздувать сообщение)
    upcoming = []
    for i in range(2, 9):
        d = today + timedelta(days=i)
        items = [x for x in holidays_on(d) if x[0] != "fun"]
        if items:
            upcoming.append(f"{d:%d.%m} — {_fmt(items)}")
    if upcoming:
        parts.append("Ближайшие дни: " + " | ".join(upcoming))

    return "[КАЛЕНДАРЬ ПРАЗДНИКОВ (используй только его, ничего не придумывай): " + ". ".join(parts) + "]"
