# ─── Православная Пасха и подвижные праздники ─────────────────
def orthodox_easter(year: int):
    """Дата православной Пасхи (по григорианскому календарю), 1900–2099."""
    a, b, c = year % 4, year % 7, year % 19
    d = (19 * c + 15) % 30
    e = (2 * a + 4 * b - d + 34) % 7
    month, day = divmod(d + e + 114, 31)
    julian = datetime(year, month, day + 1)
    return (julian + timedelta(days=13)).date()


